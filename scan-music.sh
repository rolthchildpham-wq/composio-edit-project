#!/bin/bash
# Quét public/music/<mood>/* và sinh src/lib/musicManifest.ts
# Chạy lại mỗi khi thêm/xóa file nhạc:  npm run scan-music
cd "$(dirname "$0")"
OUT=src/lib/musicManifest.ts
{
  echo "// Auto-generated by scan-music.sh — do not edit by hand"
  echo "export const musicManifest = {"
  for mood in soi-dong corporate lofi-chill trang-nghiem quang-cao; do
    echo "  \"$mood\": ["
    if [ -d "public/music/$mood" ]; then
      find "public/music/$mood" -maxdepth 1 \( -name "*.mp3" -o -name "*.m4a" -o -name "*.wav" \) | sort | while read -r f; do
        rel="${f#public/}"
        echo "    \"$rel\","
      done
    fi
    echo "  ],"
  done
  echo "} as const;"
} > "$OUT"
echo "Đã cập nhật $OUT:"
grep -c '"music/' "$OUT" | xargs echo "  số track:"
